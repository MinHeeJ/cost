       CASE WHEN d.deny THEN 'N' ELSE substr(r.p,1,1) END, CASE WHEN d.deny THEN 'N' ELSE substr(r.p,2,1) END,
       CASE WHEN d.deny THEN 'N' ELSE substr(r.p,3,1) END, CASE WHEN d.deny THEN 'N' ELSE substr(r.p,4,1) END,
