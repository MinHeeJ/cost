-- 청구별 미수금·지난 일수 (UI-13 미수금, 미수 알림)
CREATE VIEW v_bill_outstanding AS
SELECT b.bill_id,
       b.bill_no,
       b.project_id,
       p.customer_partner_id,
       b.bill_date,
       b.payment_due_date,
       b.total_amount,
       COALESCE(r.received, 0)                       AS received_amount,
       b.total_amount - COALESCE(r.received, 0)      AS outstanding_amount,
       CASE WHEN b.payment_due_date IS NOT NULL AND b.total_amount - COALESCE(r.received, 0) > 0
            THEN GREATEST(CURRENT_DATE - b.payment_due_date, 0) ELSE 0 END AS overdue_days
FROM bil_bill b
JOIN prj_project p ON p.project_id = b.project_id
LEFT JOIN (SELECT bill_id, SUM(amount) AS received FROM bil_receipt GROUP BY bill_id) r ON r.bill_id = b.bill_id
WHERE b.status = 'CONFIRM';
COMMENT ON VIEW v_bill_outstanding IS '청구별 미수금·지난 일수';

-- 사람별 월 MM 합계 (1.0 초과 경고, 가동률, 대기 원가)
CREATE VIEW v_developer_month_mm AS
SELECT a.developer_id,
       m.work_month,
       SUM(m.mm)                                                    AS total_mm,
       COUNT(*)                                                     AS project_cnt,
       CASE WHEN SUM(m.mm) > 1 THEN 'Y' ELSE 'N' END                AS over_1mm_yn,
       SUM(CASE WHEN p.contract_type IN ('MO','DP') AND a.assign_kind <> 'FREE' THEN m.mm ELSE 0 END) AS billable_mm
FROM asg_assignment_month m
JOIN asg_assignment a ON a.assignment_id = m.assignment_id AND a.status <> 'CANCELLED'
JOIN prj_project p    ON p.project_id = a.project_id
GROUP BY a.developer_id, m.work_month;
COMMENT ON VIEW v_developer_month_mm IS '사람별 월 MM 합계';

-- 투입 월별 적용 단가 (그 달 말일 이전 가장 최근 단가 이력)
CREATE VIEW v_assignment_rate_month AS
SELECT m.assignment_id,
       m.work_month,
       m.mm,
       r.bill_rate,
       r.pay_rate
FROM asg_assignment_month m
LEFT JOIN LATERAL (
  SELECT h.bill_rate, h.pay_rate
  FROM asg_rate_hist h
  WHERE h.assignment_id = m.assignment_id
    AND h.apply_from <= (to_date(m.work_month, 'YYYY-MM') + INTERVAL '1 month - 1 day')::date
  ORDER BY h.apply_from DESC
  LIMIT 1
) r ON TRUE;
COMMENT ON VIEW v_assignment_rate_month IS '투입 월별 적용 단가';

-- 영업 파트 기준 이력 중 현재 적용 줄
CREATE VIEW v_sales_part_policy_month AS
SELECT sp.part_id, sp.part_name, sp.is_hq, pp.policy_id, pp.apply_from, pp.apply_to,
       pp.leader_user_id, pp.leader_name, pp.profit_share_rate, pp.sales_fee
FROM mst_sales_part sp
JOIN mst_sales_part_policy pp ON pp.part_id = sp.part_id
WHERE pp.apply_from <= to_char(CURRENT_DATE, 'YYYY-MM')
  AND (pp.apply_to IS NULL OR pp.apply_to >= to_char(CURRENT_DATE, 'YYYY-MM'));
COMMENT ON VIEW v_sales_part_policy_month IS '영업 파트 현재 적용 기준';


