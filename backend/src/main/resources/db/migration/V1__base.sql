CREATE TABLE IF NOT EXISTS sys_menu (
    menu_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_menu_id BIGINT REFERENCES sys_menu(menu_id),
    menu_name VARCHAR(50) NOT NULL,
    screen_id VARCHAR(10) UNIQUE,
    icon VARCHAR(30),
    sort_order INT NOT NULL,
    use_yn CHAR(1) CHECK (use_yn IN ('Y', 'N')),
    mobile_yn CHAR(1) CHECK (mobile_yn IN ('Y', 'N')),
    created_at TIMESTAMP,
    created_by BIGINT,
    updated_at TIMESTAMP,
    updated_by BIGINT
);
COMMENT ON TABLE sys_menu IS '공개 탐색에 필요한 메뉴 묶음과 화면, 기기 지원 정보를 관리한다.';
COMMENT ON COLUMN sys_menu.screen_id IS 'frontend 화면 등록표 식별자 참조 의도 (FK 미선언)';
COMMENT ON COLUMN sys_menu.created_by IS '향후 사용자 식별자 참조 의도 (FK 미선언, 현재 NULL)';
COMMENT ON COLUMN sys_menu.updated_by IS '향후 사용자 식별자 참조 의도 (FK 미선언, 현재 NULL)';
COMMENT ON COLUMN sys_menu.updated_at IS '향후 메뉴 변경 시 애플리케이션에서 갱신, 현재 조회는 갱신하지 않음';

CREATE TABLE IF NOT EXISTS fin_month_close (
    close_month CHAR(7) PRIMARY KEY CHECK (close_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    status VARCHAR(10) CHECK (status IN ('OPEN', 'CLOSED')),
    closed_by BIGINT,
    closed_at TIMESTAMP,
    reopened_by BIGINT,
    reopened_at TIMESTAMP,
    reopen_reason VARCHAR(500)
);
COMMENT ON TABLE fin_month_close IS '월별 마감 상태와 마감·재개 메타데이터를 보관하며 이번 서비스는 읽기만 한다.';
COMMENT ON COLUMN fin_month_close.closed_by IS '향후 사용자 식별자 참조 의도 (FK 미선언, 현재 NULL)';
COMMENT ON COLUMN fin_month_close.reopened_by IS '향후 사용자 식별자 참조 의도 (FK 미선언, 현재 NULL)';

